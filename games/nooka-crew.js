  /* ── как помощник решает ─────────────────────────────────
     Складываем приметы тех каналов, что у него есть. Перевесило
     в плюс — отвечает «да», в минус — «нет». Поровну значит
     «не уверен»: осторожный зовёт человека, смелый решает сам. */
  function decide(work, task, has, careful) {
    var score = 0, seen = [], blind = [];
    task.clues.forEach(function (c) {
      if (has[c.ch]) { score += c.w; seen.push(c); }
      else blind.push(c);
    });
    var sure = score !== 0;
    var say = sure ? score > 0 : work.safe;     // при равенстве — осторожный ответ
    return {
      say: say, sure: sure, score: score, seen: seen, blind: blind,
      ask: !sure && careful,                    // спросить человека, а не решать самому
      right: say === task.ans,
    };
  }

  /* Чего не хватило: каналы, которые перевернули бы ответ */
  function missing(work, task, has) {
    var out = [];
    ORDER.forEach(function (ch) {
      if (has[ch]) return;
      var next = {}; ORDER.forEach(function (k) { next[k] = has[k]; });
      next[ch] = true;
      if (!decide(work, task, has, false).right && decide(work, task, next, false).right) out.push(ch);
    });
    return out;
  }

